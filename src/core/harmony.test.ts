import { describe, expect, it } from "vitest";
import {
  genitiveSuffix,
  locativeSuffix,
  personalSuffix,
  pluralSuffix,
  possessive,
  presentNegative,
  presentTense,
  questionParticle,
} from "./harmony";

// Expected forms are taken from the beginner course's worked examples.

describe("pluralSuffix", () => {
  it.each([
    ["бала", "балалар"],
    ["қала", "қалалар"],
    ["тау", "таулар"],
    ["қой", "қойлар"],
    ["үй", "үйлер"],
    ["бөлме", "бөлмелер"],
    ["компьютер", "компьютерлер"],
    ["адам", "адамдар"],
    ["қыз", "қыздар"],
    ["үстел", "үстелдер"],
    ["тіл", "тілдер"],
    ["сөз", "сөздер"],
    ["телефон", "телефондар"],
    ["кітап", "кітаптар"],
    ["мысық", "мысықтар"],
    ["ит", "иттер"],
    ["жүрек", "жүректер"],
    ["мектеп", "мектептер"],
    ["клуб", "клубтар"],
    ["велосипед", "велосипедтер"],
  ])("%s → %s", (word, plural) => {
    expect(word + pluralSuffix(word)).toBe(plural);
  });
});

